function initKeywordTicker() {
  const ticker = document.getElementById('keyword-ticker');
  if (!ticker) return;

  // Create two sets of keywords for seamless looping
  const keywordsHTML = keywords.map(kw => `<span class="keyword-item">${kw}</span>`).join('');
  
  const tickerContent = document.createElement('div');
  tickerContent.className = 'ticker-content';
  tickerContent.innerHTML = keywordsHTML + keywordsHTML; // Duplicate for seamless loop
  
  ticker.appendChild(tickerContent);
}

// Initialize when DOM is ready
document.addEventListener('DOMContentLoaded', initKeywordTicker);
